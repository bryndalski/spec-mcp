"""docs_check: read-only hygiene checks over the documentation corpus."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from .parse import _FRONTMATTER, rel

RULES = (
    "no_status",
    "unknown_status",
    "superseded_without_target",
    "superseded_by_missing",
    "supersedes_missing",
    "historical_outside_archive",
    "dead_link",
    "dead_anchor",
    "unresolved_path",
    "stale_pattern",
)
SEVERITY = {
    "unresolved_path": "info",
    "stale_pattern": "warning",
    "historical_outside_archive": "warning",
    "no_status": "error",
}

_LINK = re.compile(r"(?<!\!)\[[^\]\n]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
_INLINE_CODE = re.compile(r"`([^`\n]+)`")
_HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_PATHLIKE = re.compile(
    r"^[\w@.\-/\[\]()]+/[\w@.\-/\[\]()]*\.[A-Za-z0-9]{1,6}(?::\d+(?:-\d+)?)?$"
)


def slug(heading: str) -> str:
    """GitHub-style heading anchor."""
    s = re.sub(r"[`*_~]", "", heading.strip().lower())
    s = re.sub(r"[^\w\- ]", "", s, flags=re.UNICODE)
    return s.replace(" ", "-")


def glob_match(path: str, pattern: str) -> bool:
    """`**` crosses directories (and may match none), `*` stays inside a segment."""
    out = ""
    i = 0
    while i < len(pattern):
        c = pattern[i]
        if pattern.startswith("**/", i):
            out += "(?:.*/)?"
            i += 3
        elif pattern.startswith("**", i):
            out += ".*"
            i += 2
        elif c == "*":
            out += "[^/]*"
            i += 1
        elif c == "?":
            out += "[^/]"
            i += 1
        else:
            out += re.escape(c)
            i += 1
    return re.fullmatch(out, path) is not None


def _lines_outside_code(text: str) -> list[tuple[int, str, bool]]:
    """(line_no, line, in_fence) for every line after the front matter."""
    skip = (
        text[: _FRONTMATTER.match(text).end()].count("\n")
        if _FRONTMATTER.match(text)
        else 0
    )
    out = []
    in_fence = False
    for n, line in enumerate(text.splitlines(), start=1):
        if n <= skip:
            continue
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            out.append((n, line, True))
            continue
        out.append((n, line, in_fence))
    return out


def headings_of(text: str) -> set[str]:
    anchors: set[str] = set()
    seen: dict[str, int] = {}
    for _, line, fenced in _lines_outside_code(text):
        if fenced:
            continue
        m = _HEADING.match(line)
        if m:
            base = slug(m.group(2))
            k = seen.get(base, 0)
            seen[base] = k + 1
            anchors.add(base if k == 0 else f"{base}-{k}")
    return anchors


def check_docs(
    idx: Any, glob: str | None, checks: list[str] | None, limit: int
) -> dict[str, Any]:
    cfg = idx.cfg["docs"]
    root: Path = idx.root
    wanted = set(checks) if checks else set(RULES)
    statuses = set(cfg["statuses"])
    require_fm = bool(cfg.get("require_front_matter"))
    archive = (cfg.get("archive_dir") or "").strip("/")
    roots = [(root / r) for r in cfg.get("evidence_roots") or []] or [root]
    stale = []
    for sp in cfg.get("stale_patterns") or []:
        flags = re.IGNORECASE if "i" in str(sp.get("flags", "")) else 0
        stale.append(
            (sp, re.compile(sp["regex"], flags), set(sp.get("exclude_statuses") or []))
        )

    findings: list[dict[str, Any]] = []
    by_status: dict[str, int] = {}
    scanned = 0
    anchor_cache: dict[Path, set[str]] = {}

    def add(file: str, line: int | None, rule: str, detail: str) -> None:
        if rule in wanted:
            findings.append(
                {
                    "file": file,
                    "line": line,
                    "rule": rule,
                    "severity": SEVERITY.get(rule, "error"),
                    "detail": detail,
                }
            )

    def exists(base_dir: Path, target: str) -> Path | None:
        p = (
            (root / target.lstrip("/"))
            if target.startswith("/")
            else (base_dir / target)
        )
        p = p.resolve()
        return p if p.exists() else None

    for d in idx.doc_list:
        file = d["file"]
        if glob and not glob_match(file, glob):
            continue
        scanned += 1
        status = d.get("status")
        eff = idx.effective_status(d)
        by_status[eff] = by_status.get(eff, 0) + 1
        path = idx.resolve(file)
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        generated = "generated by spec-mcp" in "\n".join(text.splitlines()[:5])
        if status is None and require_fm and not generated:
            add(file, 1, "no_status", "front matter has no `status`")
        if status is not None and status not in statuses:
            add(
                file,
                1,
                "unknown_status",
                f"status {status!r} not in {sorted(statuses)}",
            )
        sb = d.get("superseded_by")
        if status == "superseded" and not sb:
            add(
                file,
                1,
                "superseded_without_target",
                "status superseded but no `superseded_by`",
            )
        if sb and not exists(root, sb):
            add(
                file, 1, "superseded_by_missing", f"superseded_by {sb!r} does not exist"
            )
        for s in d.get("supersedes") or []:
            if not exists(root, s):
                add(file, 1, "supersedes_missing", f"supersedes {s!r} does not exist")
        if status == "historical" and archive and not file.startswith(archive + "/"):
            add(
                file,
                1,
                "historical_outside_archive",
                f"historical document outside {archive}/",
            )

        for n, line, fenced in _lines_outside_code(text):
            for sp, rx, excl in stale:
                if eff in excl or status in excl:
                    continue
                if rx.search(line):
                    add(
                        file,
                        n,
                        "stale_pattern",
                        f"{sp['id']}: {sp.get('reason', sp['regex'])}",
                    )
            if fenced:
                continue
            for m in _LINK.finditer(_INLINE_CODE.sub(" ", line)):
                target = m.group(1)
                if re.match(r"^[a-z][a-z0-9+.\-]*:", target, re.IGNORECASE):
                    continue
                path_part, _, anchor = target.partition("#")
                path_part = path_part.split("?")[0]
                if not path_part:
                    if anchor and anchor not in headings_of(text):
                        add(
                            file,
                            n,
                            "dead_anchor",
                            f"#{anchor} not a heading in this file",
                        )
                    continue
                hit = exists(path.parent, path_part)
                if hit is None:
                    add(file, n, "dead_link", f"{target} does not exist")
                elif anchor and hit.is_file() and hit.suffix == ".md":
                    if hit not in anchor_cache:
                        anchor_cache[hit] = headings_of(
                            hit.read_text(encoding="utf-8", errors="replace")
                        )
                    if anchor not in anchor_cache[hit]:
                        add(file, n, "dead_anchor", f"{target}: no such heading")
            if "unresolved_path" in wanted:
                for m in _INLINE_CODE.finditer(line):
                    tok = m.group(1).strip()
                    if (
                        not _PATHLIKE.match(tok)
                        or any(c in tok for c in "*{}<>$")
                        or tok.startswith(("http", "~", "/"))
                        or "..." in tok
                    ):
                        continue
                    ref = re.sub(r":\d+(?:-\d+)?$", "", tok)
                    if (
                        (root / ref).exists()
                        or (path.parent / ref).exists()
                        or any((r / ref).exists() for r in roots)
                    ):
                        continue
                    add(
                        file,
                        n,
                        "unresolved_path",
                        f"`{ref}` not found from repo root, doc dir or evidence roots",
                    )

    counts: dict[str, int] = {}
    for f in findings:
        counts[f["rule"]] = counts.get(f["rule"], 0) + 1
    return {
        "checked": scanned,
        "by_status": by_status,
        "total_findings": len(findings),
        "counts_by_rule": dict(sorted(counts.items(), key=lambda kv: -kv[1])),
        "findings": findings[: max(1, limit)],
        "truncated": len(findings) > max(1, limit),
        "rules": sorted(wanted),
        "total_docs": len(idx.doc_list),
    }


def unknown_rules(checks: list[str]) -> list[str]:
    return [c for c in checks if c not in RULES]


def inbound_links(idx: Any, target: str) -> list[str]:
    """Docs that link (markdown link) to `target` (repo-relative path)."""
    tgt = (idx.root / target).resolve()
    out: list[str] = []
    for d in idx.doc_list:
        p = idx.resolve(d["file"])
        try:
            text = p.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for _, line, fenced in _lines_outside_code(text):
            if fenced:
                continue
            for m in _LINK.finditer(line):
                t = m.group(1).partition("#")[0].split("?")[0]
                if not t or re.match(r"^[a-z][a-z0-9+.\-]*:", t, re.IGNORECASE):
                    continue
                cand = (
                    (idx.root / t.lstrip("/")) if t.startswith("/") else (p.parent / t)
                ).resolve()
                if cand == tgt:
                    out.append(d["file"])
                    break
            else:
                continue
            break
    return out


__all__ = ["check_docs", "glob_match", "inbound_links", "unknown_rules", "RULES", "rel"]
