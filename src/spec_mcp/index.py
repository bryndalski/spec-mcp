"""SpecIndex: scans the three collections, caches the result in `index_file` keyed by a
fingerprint of (file list + mtimes + sizes + config), and owns the links sidecar.

Rebuild is lazy (first use / stale fingerprint) and forced after every write."""

from __future__ import annotations

import fnmatch
import glob
import hashlib
import json
import os
import re
import time
from pathlib import Path
from typing import Any

from .bm25 import BM25, tokenize
from .errors import SpecError
from .parse import chunk_doc, doc_title, parse_flows, parse_flows_json, parse_requirements, parse_requirements_json, rel

GENERATED_MARKER = "generated by spec-mcp"
CACHE_VERSION = 1


def _is_generated(path: Path) -> bool:
    try:
        with path.open(encoding="utf-8", errors="replace") as fh:
            head = "".join(fh.readline() for _ in range(5))
        return GENERATED_MARKER in head
    except OSError:
        return False


class SpecIndex:
    def __init__(self, cfg: dict[str, Any]):
        self.cfg = cfg
        self.root = Path(cfg["_root"])
        self.id_re = re.compile(cfg["requirements"]["id_pattern"])
        self.status_re = re.compile(cfg["requirements"]["status_pattern"])
        self.heading_re = re.compile(cfg["flows"]["heading_pattern"])
        self.requirements: dict[str, dict[str, Any]] = {}
        self.req_all: list[dict[str, Any]] = []  # every occurrence, incl. duplicates
        self.flows: dict[str, dict[str, Any]] = {}
        self.chunks: list[dict[str, Any]] = []
        self.doc_files = 0
        self.doc_list: list[dict[str, Any]] = []
        self.req_files: list[str] = []
        self.flow_files: list[str] = []
        self.fingerprint = ""
        self.warnings: list[dict[str, Any]] = []
        self._bm25: BM25 | None = None
        self.built_at: float | None = None

    # ---------------------------------------------------------------- paths

    def resolve(self, p: str) -> Path:
        path = Path(p)
        return path if path.is_absolute() else self.root / path

    def _expand(self, globs: list[str], exclude: list[str] | None = None) -> list[Path]:
        seen: dict[str, Path] = {}
        for g in globs:
            pattern = g if os.path.isabs(g) else str(self.root / g)
            for hit in glob.glob(pattern, recursive=True):
                p = Path(hit)
                if not p.is_file():
                    continue
                posix = p.as_posix()
                if exclude and any(fnmatch.fnmatch(posix, ex) or fnmatch.fnmatch(rel(p, self.root), ex) for ex in exclude):
                    continue
                seen[posix] = p
        return [seen[k] for k in sorted(seen)]

    def collection_files(self) -> dict[str, list[Path]]:
        docs = self._expand(self.cfg["docs"]["globs"], self.cfg["docs"].get("exclude") or [])
        reqs = self._expand(self.cfg["requirements"]["globs"], self.cfg["requirements"].get("exclude") or [])
        wf = self.resolve(self.cfg["requirements"]["write_file"])
        if wf.is_file() and wf not in reqs:
            reqs.append(wf)
        reqs = [p for p in reqs if p.suffix == ".json" or not _is_generated(p)]
        flows = self._expand(self.cfg["flows"]["globs"], self.cfg["flows"].get("exclude") or [])
        fw = self.resolve(self.cfg["flows"]["write_file"])
        if fw.is_file() and fw not in flows:
            flows.append(fw)
        flows = [p for p in flows if p.suffix == ".json" or not _is_generated(p)]
        return {"docs": docs, "requirements": reqs, "flows": flows}

    # ---------------------------------------------------------------- cache

    def _fingerprint(self, files: dict[str, list[Path]]) -> str:
        h = hashlib.sha256()
        h.update(json.dumps({k: v for k, v in self.cfg.items() if not k.startswith("_")}, sort_keys=True).encode())
        h.update(str(CACHE_VERSION).encode())
        for coll in ("docs", "requirements", "flows"):
            for p in files[coll]:
                try:
                    st = p.stat()
                except OSError:
                    continue
                h.update(f"{coll}|{p.as_posix()}|{st.st_mtime_ns}|{st.st_size}\n".encode())
        return h.hexdigest()

    @property
    def cache_path(self) -> Path:
        return self.resolve(self.cfg["index_file"])

    def ensure(self, force: bool = False) -> str:
        """Make the in-memory index current. Returns 'cache', 'rebuilt' or 'current'."""
        files = self.collection_files()
        fp = self._fingerprint(files)
        if not force and self.fingerprint == fp and self.built_at is not None:
            return "current"
        if not force and self.cache_path.is_file():
            try:
                data = json.loads(self.cache_path.read_text(encoding="utf-8"))
                if data.get("fingerprint") == fp and data.get("version") == CACHE_VERSION:
                    self._load(data)
                    self.built_at = self.cache_path.stat().st_mtime
                    return "cache"
            except (OSError, json.JSONDecodeError, KeyError, TypeError):
                pass
        self._build(files, fp)
        return "rebuilt"

    def _load(self, data: dict[str, Any]) -> None:
        self.fingerprint = data["fingerprint"]
        self.req_all = data["requirements"]
        self.requirements = {}
        for r in self.req_all:
            self.requirements.setdefault(r["id"], r)
        self.flows = {f["id"]: f for f in data["flows"]}
        self.chunks = data["chunks"]
        self.doc_list = data["docs"]
        self.doc_files = len(self.doc_list)
        self.req_files = data["req_files"]
        self.flow_files = data["flow_files"]
        self.warnings = data.get("warnings", [])
        self._bm25 = None

    def _build(self, files: dict[str, list[Path]], fp: str) -> None:
        self.req_all = []
        self.warnings = []
        for p in files["requirements"]:
            if p.suffix == ".json":
                self.req_all.extend(parse_requirements_json(p, self.id_re, self.root, self.warnings))
            else:
                self.req_all.extend(parse_requirements(p, self.id_re, self.status_re, self.root))
        self.requirements = {}
        for r in self.req_all:
            self.requirements.setdefault(r["id"], r)
        self.flows = {}
        for p in files["flows"]:
            parsed = parse_flows_json(p, self.id_re, self.root, self.warnings) if p.suffix == ".json" else parse_flows(p, self.heading_re, self.id_re, self.root)
            for f in parsed:
                self.flows.setdefault(f["id"], f)
        self.chunks = []
        self.doc_list = []
        for p in files["docs"]:
            self.chunks.extend(chunk_doc(p, self.root))
            try:
                size = p.stat().st_size
            except OSError:
                size = 0
            self.doc_list.append({"file": rel(p, self.root), "title": doc_title(p), "bytes": size})
        self.doc_files = len(self.doc_list)
        self.req_files = [rel(p, self.root) for p in files["requirements"]]
        self.flow_files = [rel(p, self.root) for p in files["flows"]]
        self.fingerprint = fp
        self._bm25 = None
        self.built_at = time.time()
        payload = {
            "version": CACHE_VERSION,
            "fingerprint": fp,
            "built_at": self.built_at,
            "requirements": self.req_all,
            "flows": list(self.flows.values()),
            "chunks": self.chunks,
            "docs": self.doc_list,
            "req_files": self.req_files,
            "warnings": self.warnings,
            "flow_files": self.flow_files,
        }
        try:
            self.cache_path.parent.mkdir(parents=True, exist_ok=True)
            self.cache_path.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")
        except OSError as e:
            raise SpecError("io", f"cannot write index cache {self.cache_path}: {e}", retryable=True) from e

    def invalidate(self) -> None:
        self.fingerprint = ""
        self.built_at = None

    def age_seconds(self) -> float | None:
        if self.built_at is None:
            return None
        return round(time.time() - self.built_at, 1)

    # ---------------------------------------------------------------- search

    def bm25(self) -> BM25:
        if self._bm25 is None:
            self._bm25 = BM25([tokenize(f"{c['heading']}\n{c['text']}") for c in self.chunks])
        return self._bm25

    # ---------------------------------------------------------------- links sidecar

    @property
    def links_path(self) -> Path:
        return self.resolve(self.cfg["links_file"])

    def load_links(self) -> dict[str, dict[str, list[str]]]:
        p = self.links_path
        if not p.is_file():
            return {}
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as e:
            raise SpecError("io", f"cannot read links sidecar {p}: {e}") from e
        return data if isinstance(data, dict) else {}

    def links_for(self, req_id: str) -> dict[str, list[str]]:
        """Effective links: inline (JSON item) merged with the sidecar (markdown items)."""
        r = self.requirements.get(req_id) or {}
        inline = r.get("links") or {}
        entry = self.load_links().get(req_id, {}) if r.get("format") != "json" else {}
        out: dict[str, list[str]] = {}
        for k in ("flows", "docs", "tests"):
            vals = list(inline.get(k, []))
            for v in entry.get(k, []):
                if v not in vals:
                    vals.append(v)
            out[k] = vals
        return out

    def add_link(self, req_id: str, target_type: str, target: str) -> dict[str, list[str]]:
        key = {"flow": "flows", "doc": "docs", "test": "tests"}[target_type]
        r = self.requirements.get(req_id)
        if r and r.get("format") == "json":
            from .jsonstore import read_items, write_items

            path = self.resolve(r["file"])
            items = read_items(path)
            for it in items:
                if str(it.get("id")) == req_id:
                    links = it.setdefault("links", {})
                    bucket = links.setdefault(key, [])
                    if target not in bucket:
                        bucket.append(target)
                    break
            write_items(path, items, "requirements")
            self.invalidate()
            self.ensure(force=True)
            return self.links_for(req_id)
        data = self.load_links()
        entry = data.setdefault(req_id, {})
        bucket = entry.setdefault(key, [])
        if target not in bucket:
            bucket.append(target)
        try:
            self.links_path.write_text(json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
        except OSError as e:
            raise SpecError("io", f"cannot write links sidecar {self.links_path}: {e}", retryable=True) from e
        return self.links_for(req_id)
